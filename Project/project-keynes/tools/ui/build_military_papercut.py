"""Build Project.Keynes military papercut sticker art.

The military sheet is generated from five dedicated source atlases in the same
wax-crayon / graphite / scissor-cut paper language as the general UI icons.
Source cells are located from transparent gutters instead of relying on an
equal-pixel grid, then each complete sticker is fitted into a 320px runtime
cell with a fine pencil outline and a soft contact shadow.

Inputs : assets/military/papercut/source/*.png
Outputs: assets/military/papercut/military_atlas_v1.png
         assets/military/papercut/source-manifest.json
         assets/military/papercut/regions.json
         assets/military/papercut/README.md

Godot binds every sticker with an AtlasTexture generated by
`build_military_papercut_tres()`; IconCatalog references those .tres files.

Usage: python tools/ui/build_military_papercut.py [--check]
"""
from __future__ import annotations

