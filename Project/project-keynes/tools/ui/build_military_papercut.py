def _split_edges(profile: list[int], count: int) -> list[int]:
    """Find transparent gutters near nominal lines; generated art is not grid-aligned."""
    length = len(profile)
    edges = [0]
    for index in range(1, count):
        expected = index * length / count
        span = length / count * 0.24
        candidates = range(max(1, round(expected - span)),
                           min(length - 1, round(expected + span)))
        if not candidates:
            raise SystemExit(f"cannot split source profile of {length}px into {count} cells")
        edge = min(
            candidates,
            key=lambda pos: sum(profile[max(0, pos - 3):pos + 4])
            + abs(pos - expected) * 0.02,
        )
        edges.append(edge)
    return edges + [length]


@lru_cache(maxsize=None)
def _source_image(name: str) -> Image.Image:
    path = SOURCE / f"{name}.png"
    if not path.exists():
        raise SystemExit(f"missing military source atlas: {path}")
    return Image.open(path).convert("RGBA")


def _source_cell(name: str, cell_index: int) -> tuple[int, int, int, int]:
    spec = SOURCE_SHEETS[name]
    cols, rows = spec["columns"], spec["rows"]
    if not 0 <= cell_index < cols * rows:
        raise SystemExit(f"source cell out of range: {name}[{cell_index}]")
    image = _source_image(name)
    alpha = np.asarray(image.getchannel("A"))
    row_profile = np.count_nonzero(alpha > 16, axis=1).tolist()
    row_edges = _split_edges(row_profile, rows)
    row = cell_index // cols
    col = cell_index % cols
    y0, y1 = row_edges[row], row_edges[row + 1]
    col_profile = np.count_nonzero(alpha[y0:y1] > 16, axis=0).tolist()
    col_edges = _split_edges(col_profile, cols)
    return col_edges[col], y0, col_edges[col + 1], y1


def _source_tile(name: str, semantic: str) -> Image.Image:
    spec = SOURCE_SHEETS[name]
    try:
        cell_index = spec["semantics"].index(semantic)
    except ValueError as error:
        raise SystemExit(f"{semantic} is not declared in {name}") from error
    x0, y0, x1, y1 = _source_cell(name, cell_index)
    cell = _source_image(name).crop((x0, y0, x1, y1))
    alpha = np.asarray(cell.getchannel("A")) > 16
    labels, count = ndimage.label(alpha, structure=np.ones((3, 3), dtype=bool))
    if count == 0:
        raise SystemExit(f"empty source tile {name}:{semantic} at cell {cell_index}")
    sizes = ndimage.sum(alpha, labels, range(1, count + 1))
    sticker = np.argmax(sizes) + 1
    ys, xs = np.nonzero(labels == sticker)
    tile = cell.crop((int(xs.min()), int(ys.min()),
                      int(xs.max()) + 1, int(ys.max()) + 1))
    if tile.width < 48 or tile.height < 48:
        raise SystemExit(f"implausibly small source tile {name}:{semantic} {tile.size}")
    return tile


def _fibre_field(size: tuple[int, int], seed: int) -> np.ndarray:
    """Organic paper fibre noise: lumpy low frequencies plus cut-edge grain."""
    width, height = size
    rng = np.random.default_rng(seed)
    small = (rng.random((9, 9)) * 255).astype(np.uint8)
    lumps = np.array(Image.fromarray(small).resize((width, height), Image.BICUBIC),
                     dtype=np.float32) / 255.0
    grain = rng.random((height, width)).astype(np.float32)
    return lumps * 0.72 + grain * 0.28


def _expand(alpha: np.ndarray, reach: int, field: np.ndarray) -> np.ndarray:
    """Union of alpha blurred to a soft reach, thresholded per pixel by noise."""
    if reach <= 0:
        return alpha
    src = Image.fromarray((alpha * 255).astype(np.uint8))
    soft = np.array(src.filter(ImageFilter.GaussianBlur(reach * 0.62)),
                    dtype=np.float32) / 255.0
    limit = np.clip(soft * 1.15 + 0.35 * (field - 0.5), 0.0, 1.0)
    return np.clip((limit - 0.28) * 6.0, 0.0, 1.0)


def _edge_band(mask: np.ndarray, width_px: int) -> np.ndarray:
    """Pixels within `width_px` of the silhouette edge (for the pencil line)."""
    src = Image.fromarray((mask * 255).astype(np.uint8))
    eroded: Image.Image = src
    for _ in range(width_px):
        eroded = eroded.filter(ImageFilter.MinFilter(3))
    band = np.array(src, dtype=np.float32) - np.array(eroded, dtype=np.float32)
    return np.clip(band / 255.0, 0.0, 1.0)


def _compose(key: str, src: str) -> Image.Image:
    tile = _source_tile(src, key)
    inner = CELL - (TEAR + SHADOW) * 2
    scale = min(inner / tile.size[0], inner / tile.size[1])
    size = (max(1, int(round(tile.size[0] * scale))),
            max(1, int(round(tile.size[1] * scale))))
    art = tile.resize(size, Image.LANCZOS)

    alpha = np.zeros((CELL, CELL), dtype=np.float32)
    ox = (CELL - size[0]) // 2
    oy = (CELL - size[1]) // 2
    alpha[oy:oy + size[1], ox:ox + size[0]] = \
        np.array(art)[:, :, 3].astype(np.float32) / 255.0

    seed = zlib.crc32(key.encode("utf-8")) & 0xFFFFFFFF
    field = _fibre_field((CELL, CELL), seed)
    paper = _expand(alpha, TEAR, field)
    band = _edge_band(paper, 3)
    inner_band = _edge_band(alpha, 2)

    px = np.zeros((CELL, CELL, 4), dtype=np.float32)
    px[:, :, 0] = PAPER_WHITE[0] / 255.0
    px[:, :, 1] = PAPER_WHITE[1] / 255.0
    px[:, :, 2] = PAPER_WHITE[2] / 255.0
    speckle = np.clip(field * 1.4 - 0.55, 0.0, 1.0) * 0.05
    px[:, :, 0] -= speckle
    px[:, :, 1] -= speckle * 1.05
    px[:, :, 2] -= speckle * 1.2
    px[:, :, 3] = paper

    # Pencil outline, broken up by the same fibre noise so it reads as drawn.
    line = np.clip(band * (0.55 + 0.45 * field) * 0.78 + inner_band * 0.30, 0.0, 0.9)
    for channel, value in enumerate(PENCIL):
        px[:, :, channel] = px[:, :, channel] * (1.0 - line) + (value / 255.0) * line

    # Contact shadow under the sticker, offset down-right.
    softened = Image.fromarray((np.clip(paper + band * 0.2, 0.0, 1.0) * 255).astype(np.uint8))
    shadow_mask = np.array(softened.filter(ImageFilter.GaussianBlur(SHADOW * 0.55)),
                           dtype=np.float32) / 255.0
    dx, dy = int(SHADOW * 0.45), int(SHADOW * 0.75)
    shifted = np.zeros_like(shadow_mask)
    shifted[dy:, dx:] = shadow_mask[:CELL - dy, :CELL - dx]
    shadow = np.clip(shifted - paper, 0.0, 1.0) * 0.34

    base = np.zeros((CELL, CELL, 4), dtype=np.float32)
    for channel, value in enumerate(SHADOW_INK):
        base[:, :, channel] = value / 255.0
    base[:, :, 3] = shadow
    out = base * (1.0 - px[:, :, 3:4]) + px
    out[:, :, 3] = np.clip(px[:, :, 3] + shadow * (1.0 - px[:, :, 3]), 0.0, 1.0)

    cell = Image.fromarray(np.clip(out * 255.0, 0, 255).astype(np.uint8), "RGBA")
    cell.paste(art, (ox, oy), art)
    return cell


def build() -> dict[str, list[int]]:
    OUT.mkdir(parents=True, exist_ok=True)
    entries = sorted(STICKERS.items())
    rows = (len(entries) + ATLAS_COLS - 1) // ATLAS_COLS
    sheet = Image.new("RGBA", (ATLAS_COLS * CELL, rows * CELL), (0, 0, 0, 0))
    regions: dict[str, list[int]] = {}
    for index, (key, src) in enumerate(entries):
        sheet.paste(_compose(key, src),
                    ((index % ATLAS_COLS) * CELL, (index // ATLAS_COLS) * CELL))
        regions[key] = [(index % ATLAS_COLS) * CELL, (index // ATLAS_COLS) * CELL, CELL, CELL]
    sheet.save(OUT / f"{ATLAS_NAME}.png")
    (OUT / "regions.json").write_text(json.dumps(regions, indent=1, sort_keys=True),
                                      encoding="utf-8")
    _write_source_manifest()
    (OUT / "README.md").write_text(_readme(regions), encoding="utf-8")
    return regions


def build_military_papercut_tres() -> int:
    """Emit one AtlasTexture .tres per sticker under assets/military/."""
    regions_path = OUT / "regions.json"
    if not regions_path.exists():
        return 0
    regions = json.loads(regions_path.read_text(encoding="utf-8"))
    written = 0
    for key, (x, y, w, h) in sorted(regions.items()):
        safe = key.replace(".", "_")
        path = ROOT / "assets" / "military" / f"{safe}.tres"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "[gd_resource type=\"AtlasTexture\" load_steps=2 format=3]\n\n"
            "[ext_resource type=\"Texture2D\" "
            f"path=\"res://assets/military/papercut/{ATLAS_NAME}.png\" id=\"1\"]\n\n"
            "[resource]\n"
            "atlas = ExtResource(\"1\")\n"
            f"region = Rect2({x}, {y}, {w}, {h})\n"
            "filter_clip = true\n",
            encoding="utf-8")
        written += 1
    _write_import()
    return written


def _write_import() -> None:
    """Import settings for the atlas: lossless RGBA, no mipmaps (matches icons)."""
    template = (PAPER / "ui_states_01.png.import").read_text(encoding="utf-8")
    lines = template.splitlines()
    rebuilt: list[str] = []
    for line in lines:
        if line.startswith("uid="):
            continue
        if line.startswith("path=\"res://.godot/imported/"):
            # Godot regenerates the cached path; keep `path`/`dest_files` out of
            # the hand-written file so the first import is a clean reimport.
            continue
        if line.startswith("dest_files="):
            continue
        rebuilt.append(line)
    text = "\n".join(rebuilt) + "\n"
    text = text.replace("source_file=\"res://assets/icons/paper/ui_states_01.png\"",
                        f"source_file=\"res://assets/military/papercut/{ATLAS_NAME}.png\"")
    if "source_file=" not in text:
        text = text.replace("[deps]\n",
                            f"[deps]\n\nsource_file=\"res://assets/military/papercut/{ATLAS_NAME}.png\"\n")
    (OUT / f"{ATLAS_NAME}.png.import").write_text(text, encoding="utf-8")


def _write_source_manifest() -> None:
    sheets = []
    for name, spec in SOURCE_SHEETS.items():
        cells = {}
        for index, semantic in enumerate(spec["semantics"]):
            if semantic is None:
                continue
            x0, y0, x1, y1 = _source_cell(name, index)
            cells[semantic] = [x0, y0, x1 - x0, y1 - y0]
        sheets.append(
            {
                "name": name,
                "file": f"source/{name}.png",
                "columns": spec["columns"],
                "rows": spec["rows"],
                "semantics": spec["semantics"],
                "cells": cells,
            }
        )
    manifest = {
        "generator": "built-in image_gen; see SOURCE_PROMPT_SUMMARY in build script",
        "style": SOURCE_PROMPT_SUMMARY,
        "sheets": sheets,
    }
    (OUT / "source-manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def _readme(regions: dict[str, list[int]]) -> str:
    lines = [
        "# Military papercut sticker atlas v1",
        "",
        "The military UI uses five dedicated source atlases generated in the same",
        "colored-pencil, graphite and scissor-cut paper language as the general UI",
        "icons. Sources live under `source/`; `source-manifest.json` records their",
        "semantic order, detected source-cell bounds and generation style summary.",
        "",
        "`tools/ui/build_military_papercut.py` locates each sticker from transparent",
        "gutters instead of assuming an equal-pixel grid. It then fits the complete",
        "sticker into a runtime cell with a fine pencil outline and soft contact",
        "shadow. This prevents source art from being clipped at nominal cell edges.",
        "",
        f"`{ATLAS_NAME}.png` is lossless RGBA, {ATLAS_COLS} columns of {CELL}px cells.",
        "Each sticker is bound by an `AtlasTexture` at `assets/military/<key>.tres`",
        "and referenced through `IconCatalog`.",
        "",
        "| key | cell (x, y, w, h) |",
        "| --- | --- |",
    ]
    for key in sorted(regions):
        x, y, w, h = regions[key]
        lines.append(f"| `{key}` | {x}, {y}, {w}, {h} |")
    return "\n".join(lines) + "\n"


def check() -> int:
    target = OUT / f"{ATLAS_NAME}.png"
    failures = []
    for name in SOURCE_SHEETS:
        if not (SOURCE / f"{name}.png").exists():
            failures.append(f"missing source {name}.png")
    if not target.exists():
        failures.append(f"missing {target}")
    regions_path = OUT / "regions.json"
    if not regions_path.exists():
        failures.append(f"missing {regions_path}")
    source_manifest = OUT / "source-manifest.json"
    if not source_manifest.exists():
        failures.append(f"missing {source_manifest}")
    if failures:
        for failure in failures:
            print(f"[military-papercut] FAIL: {failure}")
        return 1
    image = Image.open(target).convert("RGBA")
    regions = json.loads(regions_path.read_text(encoding="utf-8"))
    expected = set(STICKERS)
    actual = set(regions)
    if actual != expected:
        failures.append(f"region keys differ: missing={sorted(expected - actual)} extra={sorted(actual - expected)}")
    for key, (x, y, w, h) in regions.items():
        if w != CELL or h != CELL:
            failures.append(f"{key} has non-cell region {w}x{h}")
        if x < 0 or y < 0 or x + w > image.width or y + h > image.height:
            failures.append(f"{key} region lies outside atlas")
            continue
        alpha = np.asarray(image.crop((x, y, x + w, y + h)).getchannel("A"))
        visible = alpha > 16
        if not visible.any():
            failures.append(f"{key} has an empty runtime cell")
            continue
        if visible[0].any() or visible[-1].any() or visible[:, 0].any() or visible[:, -1].any():
            failures.append(f"{key} touches its runtime cell edge")
        if not (ROOT / "assets/military" / f"{key.replace('.', '_')}.tres").exists():
            failures.append(f"{key} has no AtlasTexture resource")
    if failures:
        for failure in failures:
            print(f"[military-papercut] FAIL: {failure}")
        return 1
    print(f"[military-papercut] PASS: {len(regions)} complete stickers, "
          f"{image.width}x{image.height}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check()
    regions = build()
    written = build_military_papercut_tres()
    print(f"wrote {len(regions)} stickers and {written} AtlasTexture resources to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
