def is_cjk(s):
    return any('\u4e00' <= ch <= '\u9fff' for ch in s)

changed = []
skipped_cn = 0
misses = []

for kind, d in dirs.items():
    full = os.path.join(base, d)
    if not os.path.isdir(full):
        continue
    for fn in sorted(os.listdir(full)):
        if not fn.endswith(".tres"):
            continue
        stem = fn[:-5]
        p = os.path.join(full, fn)
        txt = open(p, encoding="utf-8", newline="").read()
        m = re.search(r'^(\s*display_name\s*=\s*)"[^"]*"', txt, re.MULTILINE)
        if not m:
            continue
        old = re.search(r'"([^"]*)"', m.group(0)).group(1)
        # Skip already-Chinese
        if old and is_cjk(old):
            skipped_cn += 1
            continue
        if stem not in T:
            misses.append((kind, fn, old))
            continue
        new = T[stem]
        new_txt = txt[:m.start()] + m.group(1) + '"%s"' % new + txt[m.end():]
        open(p, "w", encoding="utf-8", newline="").write(new_txt)
        changed.append((kind, stem, old, new))

# Report
print("CHANGED:", len(changed))
print("SKIPPED (already CN):", skipped_cn)
print("MISSES (EN but no translation):", len(misses))
for kind, fn, old in misses:
    print("  MISS", kind, fn, old)

# Write CSV deliverable
import csv
out = os.path.join("D:/Godot/ProjectKeynes/Project.Keynes/tmp", "display_name_translations.csv")
with open(out, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f)
    w.writerow(["kind", "id", "old_display_name_en", "new_display_name_cn"])
    for kind, stem, old, new in changed:
        w.writerow([kind, stem, old, new])
print("CSV written:", out)
