#!/usr/bin/env python3
"""Static server for the Godot Web export in WebBuild/.

Plain `python -m http.server` is not enough for a Godot web build:

1. Cross-origin isolation. A threads-enabled export needs SharedArrayBuffer,
   which browsers only hand out to pages served with both
   `Cross-Origin-Opener-Policy: same-origin` and
   `Cross-Origin-Embedder-Policy: require-corp`. Without them the engine
   aborts on startup with "Cross-Origin Isolation ... SharedArrayBuffer".
   The current Web preset is nothreads and does not strictly need these, but
   sending them anyway keeps the threads variant working from the same server.

2. MIME types. Python's default map has no entry for .wasm or .pck, so the
   browser refuses the streaming WebAssembly instantiation path and Godot
   falls back to a slower one — or fails outright.

3. Size on the wire. The release export is ~146 MB of raw bytes; the engine
   wasm alone is ~38 MB and compresses to ~25%. This server negotiates
   br/gzip per request:

   * a pre-compressed sidecar (`<file>.br` / `<file>.gz`, generated by
     `--precompress`) wins whenever it is not older than its source;
   * otherwise compressible files up to `--max-inline-mb` are compressed in
     memory and memoized in a small LRU, so a reload does not pay again;
   * the .pck is NOT compressed inline by default: it is ~88 MB and only
     ~16% compressible (it already carries VRAM-compressed textures), so
     re-compressing it per request would burn CPU for little gain. Give it a
     sidecar with `--precompress`, or opt in with `--inline-pck`.

4. Caching. The export is rebuilt constantly during bring-up and the .wasm /
   .pck filenames never change, so a long max-age would silently mask a fresh
   build. Every response therefore carries a strong ETag (content hash from
   `manifest.json` when it matches the file, else size+mtime) and
   `Cache-Control: no-cache`, which means "revalidate, then reuse": an
   unchanged file costs one 304 instead of 146 MB. `--immutable` (or a
   request carrying `?v=<hash>`) switches to the long immutable policy for
   real deployments under a versioned directory.

Besides serving files, the server keeps the browser-to-agent event channel:
the page POSTs JSON events to `/_log`, which are appended to
`tmp/web_events.jsonl` so the agent can tail load progress / calendar
advancement / stall warnings instead of polling screenshots.

Usage:
    python tools/serve_web.py [--port 8060] [--root WebBuild]
    python tools/serve_web.py --no-compress            # measure the raw path
    python tools/serve_web.py --immutable              # production-like caching
    python tools/serve_web.py --precompress            # write .br/.gz sidecars
"""

from __future__ import annotations

import argparse
import collections
import functools
import gzip
import http.server
import json
import os
import pathlib
import socketserver
import time
import urllib.parse

try:  # optional: brotli is ~3x better than gzip on wasm
    import brotli as _brotli
except ImportError:  # pragma: no cover - depends on the interpreter
    _brotli = None

EXTRA_MIME_TYPES = {
    ".wasm": "application/wasm",
    ".pck": "application/octet-stream",
    ".js": "text/javascript",
    ".mjs": "text/javascript",
    ".worklet.js": "text/javascript",
    ".json": "application/json",
    ".webmanifest": "application/manifest+json",
}

# Extensions worth compressing. Everything here is text or wasm; PNG/JPEG/woff2
# are already compressed and must stay untouched.
# `.bank` 是例外里唯一值得压的二进制：FMOD bank = Vorbis 采样 + 未压缩的元数据/
# 事件表，实测 brotli q9 到 77%（Music_stone 8.84 -> 6.82 MB），比 PNG 那种几乎
# 压不动的东西划算得多。
COMPRESSIBLE = {
    ".wasm", ".js", ".mjs", ".pck", ".json", ".html", ".css", ".svg", ".txt",
    ".xml", ".map", ".webmanifest", ".bank",
}

SIDECAR_SUFFIX = {"br": ".br", "gzip": ".gz"}
ENCODING_HEADER = {"br": "br", "gzip": "gzip"}

INLINE_MAX_BYTES = 32 * 1024 * 1024
MEMO_BUDGET_BYTES = 256 * 1024 * 1024


def human_bytes(n: float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.2f} {unit}"
        n /= 1024
    return f"{n} B"


# --------------------------------------------------------------------------
# manifest.json (generated by the export pipeline)
# --------------------------------------------------------------------------
class Manifest:
    """`<root>/manifest.json` -> per-file sha256, used for strong ETags.

    A stale manifest (file rebuilt without regenerating it) would pin a wrong
    ETag and could serve stale-but-valid-looking caches, so an entry is only
    trusted when both size and mtime still match the file on disk.
    """

    def __init__(self, path: pathlib.Path) -> None:
        self.path = path
        self.files: dict[str, dict] = {}
        self.mtime = 0.0
        self.reload()

    def reload(self) -> None:
        try:
            st = self.path.stat()
        except OSError:
            self.files = {}
            self.mtime = 0.0
            return
        self.mtime = st.st_mtime
        try:
            payload = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            self.files = {}
            return
        files = payload.get("files") if isinstance(payload, dict) else None
        self.files = files if isinstance(files, dict) else {}

    def maybe_reload(self) -> None:
        try:
            mtime = self.path.stat().st_mtime
        except OSError:
            mtime = 0.0
        if mtime != self.mtime:
            self.reload()

    def etag_for(self, rel: str, st: os.stat_result) -> str | None:
        self.maybe_reload()
        entry = self.files.get(rel) or self.files.get(rel.replace(os.sep, "/"))
        if not entry:
            return None
        digest = entry.get("sha256")
        if not digest:
            return None
        # Trust only when the manifest describes *this* build of the file.
        size = entry.get("size")
        if size is not None and int(size) != st.st_size:
            return None
        mtime = entry.get("mtime_ns")
        if mtime is not None and abs(int(mtime) - st.st_mtime_ns) > 2_000_000:
            return None
        return '"' + str(digest) + '"'


# --------------------------------------------------------------------------
# compression
# --------------------------------------------------------------------------
def compress_bytes(data: bytes, encoding: str, quality: int) -> bytes:
    if encoding == "br":
        if _brotli is None:
            raise RuntimeError("brotli module is not installed")
        return _brotli.compress(data, quality=quality, lgwin=22)
    if encoding == "gzip":
        # mtime=0 keeps the output byte-identical between runs.
        return gzip.compress(data, compresslevel=quality, mtime=0)
    raise ValueError(encoding)


def parse_accept_encoding(header: str | None) -> list[str]:
    """Return our preferred encodings that the client accepts, best first."""
    if not header:
        return []
    scores: dict[str, float] = {}
    for part in header.split(","):
        piece = part.strip()
        if not piece:
            continue
        bits = piece.split(";")
        name = bits[0].strip().lower()
        q = 1.0
        for bit in bits[1:]:
            bit = bit.strip()
            if bit.startswith("q="):
                try:
                    q = float(bit[2:])
                except ValueError:
                    q = 1.0
        if name == "br":
            scores["br"] = q
        elif name in ("gzip", "x-gzip"):
            scores["gzip"] = max(scores.get("gzip", 0.0), q)
        elif name == "*" and q > 0:
            scores.setdefault("gzip", q * 0.5)
    allowed = [(q, enc) for enc, q in scores.items() if q > 0]
    # Ties prefer brotli (better ratio); the client's q values still win.
    allowed.sort(key=lambda item: (-item[0], 0 if item[1] == "br" else 1))
    return [enc for _, enc in allowed]


class EncodingCache:
    """Small LRU for inline-compressed bodies, keyed by (path, mtime, size, enc)."""

    def __init__(self, budget: int = MEMO_BUDGET_BYTES) -> None:
        self.budget = budget
        self.entries: collections.OrderedDict = collections.OrderedDict()
        self.bytes = 0

    def get(self, key: tuple) -> bytes | None:
        body = self.entries.get(key)
        if body is None:
            return None
        self.entries.move_to_end(key)
        return body

    def put(self, key: tuple, body: bytes) -> None:
        if key in self.entries:
            self.bytes -= len(self.entries.pop(key))
        self.entries[key] = body
        self.bytes += len(body)
        while self.bytes > self.budget and len(self.entries) > 1:
            _, evicted = self.entries.popitem(last=False)
            self.bytes -= len(evicted)

    def clear(self) -> None:
        self.entries.clear()
        self.bytes = 0


# --------------------------------------------------------------------------
# request handler
# --------------------------------------------------------------------------
class GodotWebRequestHandler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {
        **http.server.SimpleHTTPRequestHandler.extensions_map,
        **EXTRA_MIME_TYPES,
    }

    # 浏览器 -> agent 的单向事件通道：页面把 JSON 事件 POST 到 /_log，
    # 这里追加到 tmp/web_events.jsonl。agent 侧 `tail` 这个文件即可实时看到
    # 加载进度/日历推进/卡死告警，不需要截图轮询。
    event_log: pathlib.Path | None = None
    _event_seq = 0

    # Server-wide switches, filled in from argv by main().
    compress_enabled = True
    compress_quality = 6
    inline_max_bytes = INLINE_MAX_BYTES
    inline_pck = False
    cache_control_enabled = True
    immutable = False
    manifest: Manifest | None = None
    memo = EncodingCache()

    # ---- event channel ----------------------------------------------------
    def do_POST(self) -> None:  # noqa: N802 - http.server naming
        if not self.path.startswith("/_log"):
            self.send_error(404)
            return
        length = int(self.headers.get("Content-Length", "0") or 0)
        payload = self.rfile.read(length) if length > 0 else b"{}"
        if self.event_log is not None:
            try:
                record = json.loads(payload.decode("utf-8", "replace"))
            except json.JSONDecodeError:
                record = {"raw": payload.decode("utf-8", "replace")}
            record["t_wall"] = time.strftime("%H:%M:%S")
            with self.event_log.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(record, ensure_ascii=False) + "\n")
        self.send_response(204)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()

    def do_GET(self) -> None:  # noqa: N802 - http.server naming
        if self.path.startswith("/_log"):
            self._serve_event_log()
            return
        self._serve_static(head_only=False)

    def do_HEAD(self) -> None:  # noqa: N802 - http.server naming
        if self.path.startswith("/_log"):
            self.send_error(404)
            return
        self._serve_static(head_only=True)

    def _serve_event_log(self) -> None:
        records: list[str] = []
        if self.event_log is not None and self.event_log.exists():
            records = self.event_log.read_text(encoding="utf-8").splitlines()
        body = ("[" + ",".join(records) + "]").encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    # ---- static files -----------------------------------------------------
    def _serve_static(self, head_only: bool) -> None:
        path = self.translate_path(self.path)
        if os.path.isdir(path):
            index = os.path.join(path, "index.html")
            if os.path.isfile(index):
                path = index
            else:
                self.send_error(404, "Directory listing is disabled")
                return
        try:
            st = os.stat(path)
        except OSError:
            self.send_error(404, "File not found")
            return

        etag = self._etag(path, st)
        if self._not_modified(etag):
            self.send_response(304)
            self.send_header("ETag", etag)
            self._send_cache_headers()
            self.send_header("Vary", "Accept-Encoding")
            self.end_headers()
            return

        encoding, body = self._encoded_body(path, st)
        payload_len = len(body) if body is not None else st.st_size
        self.send_response(200)
        self.send_header("Content-Type", self.guess_type(path))
        if encoding:
            self.send_header("Content-Encoding", ENCODING_HEADER[encoding])
        self.send_header("Vary", "Accept-Encoding")
        self.send_header("Content-Length", str(payload_len))
        self.send_header("ETag", etag)
        self._send_cache_headers()
        self.end_headers()
        if head_only:
            return
        try:
            if body is None:
                with open(path, "rb") as handle:
                    while True:
                        chunk = handle.read(256 * 1024)
                        if not chunk:
                            break
                        self.wfile.write(chunk)
            else:
                self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError):
            # The browser closing the tab mid-download is not an error.
            pass

    def _etag(self, path: str, st: os.stat_result) -> str:
        if self.manifest is not None:
            try:
                rel = os.path.relpath(path, self.directory).replace(os.sep, "/")
            except ValueError:
                rel = os.path.basename(path)
            digest = self.manifest.etag_for(rel, st)
            if digest:
                return digest
        return '"%x-%x"' % (st.st_size, st.st_mtime_ns)

    def _not_modified(self, etag: str) -> bool:
        header = self.headers.get("If-None-Match")
        if not header:
            return False
        if header.strip() == "*":
            return True
        for token in header.split(","):
            token = token.strip()
            if token == etag:
                return True
            # Tolerate the weak form W/"...".
            if token.startswith("W/") and token[2:].strip() == etag:
                return True
        return False

    def _send_cache_headers(self) -> None:
        if not self.cache_control_enabled:
            return
        if self.immutable or self._has_version_query():
            self.send_header("Cache-Control", "public, max-age=31536000, immutable")
        else:
            # `no-cache` means "revalidate before reuse": a rebuild is visible on
            # the next refresh (the original no-store intent) while an unchanged
            # file costs a 304 instead of 146 MB.
            self.send_header("Cache-Control", "no-cache")

    def _has_version_query(self) -> bool:
        query = urllib.parse.urlsplit(self.path).query
        if not query:
            return False
        params = urllib.parse.parse_qs(query)
        return any(key in params for key in ("v", "hash", "rev"))

    def _encoded_body(self, path: str, st: os.stat_result) -> tuple[str | None, bytes | None]:
        """(encoding, body). `body is None` means "stream the file as-is"."""
        suffix = os.path.splitext(path)[1].lower()
        if not self.compress_enabled or suffix not in COMPRESSIBLE:
            return None, None
        accepted = parse_accept_encoding(self.headers.get("Accept-Encoding"))
        for encoding in accepted:
            sidecar = self._sidecar(path, encoding, st)
            if sidecar is not None:
                return encoding, sidecar
        # The .pck is ~88 MB and only ~16% compressible: it is served as-is
        # unless a sidecar exists (see the module docstring).
        if suffix == ".pck" and not self.inline_pck:
            return None, None
        if st.st_size > self.inline_max_bytes:
            return None, None
        encoding = self._inline_encoding(accepted)
        if not encoding:
            return None, None
        key = (path, st.st_mtime_ns, st.st_size, encoding)
        cached = self.memo.get(key)
        if cached is not None:
            return encoding, cached
        try:
            with open(path, "rb") as handle:
                raw = handle.read()
        except OSError:
            return None, None
        try:
            body = compress_bytes(raw, encoding, self.compress_quality)
        except RuntimeError:
            return None, None
        self.memo.put(key, body)
        return encoding, body

    def _inline_encoding(self, accepted: list[str]) -> str | None:
        if _brotli is not None and "br" in accepted:
            return "br"
        if "gzip" in accepted:
            return "gzip"
        return None

    def _sidecar(self, path: str, encoding: str, st: os.stat_result) -> bytes | None:
        sidecar_path = path + SIDECAR_SUFFIX[encoding]
        try:
            sidecar_st = os.stat(sidecar_path)
        except OSError:
            return None
        if sidecar_st.st_mtime_ns + 1_000_000 < st.st_mtime_ns:
            return None  # older than its source: the rebuild wins
        try:
            with open(sidecar_path, "rb") as handle:
                return handle.read()
        except OSError:
            return None

    # ---- headers every response carries ----------------------------------
    def end_headers(self) -> None:
        self.send_header("Cross-Origin-Opener-Policy", "same-origin")
        self.send_header("Cross-Origin-Embedder-Policy", "require-corp")
        self.send_header("Cross-Origin-Resource-Policy", "same-origin")
        self.send_header("X-Content-Type-Options", "nosniff")
        super().end_headers()


class ReusableTCPServer(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


# --------------------------------------------------------------------------
# --precompress
# --------------------------------------------------------------------------
def run_precompress(root: pathlib.Path, quality: int, gzip_quality: int) -> int:
    targets: list[pathlib.Path] = []
    for entry in sorted(root.iterdir()):
        if not entry.is_file():
            continue
        if entry.suffix.lower() not in COMPRESSIBLE:
            continue
        if entry.name.endswith((".br", ".gz")):
            continue
        targets.append(entry)
    if not targets:
        print(f"nothing to compress in {root}")
        return 1
    raw_before = 0
    wire_after = 0
    for entry in targets:
        st = entry.stat()
        raw_before += st.st_size
        best = st.st_size
        wrote: list[str] = []
        for encoding, suffix, q in (("br", ".br", quality), ("gzip", ".gz", gzip_quality)):
            if encoding == "br" and _brotli is None:
                continue
            sidecar = entry.with_name(entry.name + suffix)
            if sidecar.exists() and sidecar.stat().st_mtime_ns + 1_000_000 >= st.st_mtime_ns:
                best = min(best, sidecar.stat().st_size)
                wrote.append(f"{suffix} (cached)")
                continue
            data = entry.read_bytes()
            started = time.time()
            try:
                body = compress_bytes(data, encoding, q)
            except RuntimeError as exc:
                print(f"  {entry.name}{suffix}: {exc}")
                continue
            sidecar.write_bytes(body)
            best = min(best, len(body))
            wrote.append(f"{suffix} {len(body) / 1048576:.2f}MB"
                         f" ({100.0 * len(body) / max(1, len(data)):.1f}%, {time.time() - started:.1f}s)")
        wire_after += best
        print(f"{entry.name:52s} {st.st_size / 1048576:7.2f} MB -> "
              f"{best / 1048576:7.2f} MB   " + ", ".join(wrote))
    print(f"\nTOTAL {raw_before / 1048576:.2f} MB -> {wire_after / 1048576:.2f} MB "
          f"({100.0 * wire_after / max(1, raw_before):.1f}%)")
    return 0


def main() -> int:
    repo_root = pathlib.Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--port", type=int, default=8060)
    parser.add_argument("--root", default=str(repo_root / "WebBuild"))
    parser.add_argument("--events", default=str(repo_root / "tmp" / "web_events.jsonl"),
                        help="事件流落盘位置；debug/release 两个服务各用一份，避免交织")
    parser.add_argument("--no-truncate", action="store_true",
                        help="启动时不清空事件流（多服务共用同一个文件时用）")
    parser.add_argument("--no-compress", action="store_true",
                        help="关闭 br/gzip 协商，按原样发送（用于对比体积）")
    parser.add_argument("--no-cache-control", action="store_true",
                        help="不发 Cache-Control / ETag（排查缓存问题时用）")
    parser.add_argument("--immutable", action="store_true",
                        help="发 public, max-age=31536000, immutable（部署到版本化目录时用）")
    parser.add_argument("--max-inline-mb", type=float, default=INLINE_MAX_BYTES / 1048576,
                        help="不超过该大小的文件可内存压缩并缓存（默认 32）")
    parser.add_argument("--inline-pck", action="store_true",
                        help="允许对 .pck 也做即时压缩（默认只认 .br/.gz sidecar）")
    parser.add_argument("--compress-quality", type=int, default=6,
                        help="即时压缩质量（brotli/gzip 共用，默认 6）")
    parser.add_argument("--precompress", action="store_true",
                        help="只生成 .br/.gz sidecar 后退出（供静态托管使用）")
    parser.add_argument("--precompress-quality", type=int, default=11)
    parser.add_argument("--precompress-gzip-quality", type=int, default=9)
    args = parser.parse_args()

    root = pathlib.Path(args.root).resolve()
    if not root.is_dir():
        parser.error(f"root directory does not exist: {root}")

    if args.precompress:
        return run_precompress(root, args.precompress_quality, args.precompress_gzip_quality)

    log_dir = repo_root / "tmp"
    log_dir.mkdir(parents=True, exist_ok=True)
    event_path = pathlib.Path(args.events)
    if not event_path.is_absolute():
        event_path = repo_root / event_path
    event_path.parent.mkdir(parents=True, exist_ok=True)

    handler_cls = GodotWebRequestHandler
    handler_cls.event_log = event_path
    handler_cls.compress_enabled = not args.no_compress
    handler_cls.compress_quality = max(1, args.compress_quality)
    handler_cls.inline_pck = args.inline_pck
    handler_cls.inline_max_bytes = int(args.max_inline_mb * 1048576)
    handler_cls.cache_control_enabled = not args.no_cache_control
    handler_cls.immutable = args.immutable
    handler_cls.manifest = Manifest(root / "manifest.json")

    if not args.no_truncate:
        event_path.write_text("", encoding="utf-8")

    handler = functools.partial(handler_cls, directory=str(root))
    with ReusableTCPServer(("127.0.0.1", args.port), handler) as httpd:
        entry = next(iter(sorted(root.glob("*.html"))), None)
        url = f"http://127.0.0.1:{args.port}/"
        print(f"Serving {root}")
        print(f"  {url}{entry.name if entry else ''}")
        print("  cross-origin isolation: on")
        if args.no_compress:
            print("  compression: off")
        else:
            extra = ", pck inline" if args.inline_pck else ", pck sidecar-only"
            print(f"  compression: br/gzip, inline<={args.max_inline_mb:.0f}MB{extra}")
        print("  caching: " + ("off" if args.no_cache_control else
                               ("immutable" if args.immutable else "no-cache + ETag")))
        if not _brotli:
            print("  note: the brotli module is missing, only gzip is offered")
        print(f"  event log: {handler_cls.event_log}")
        print("Ctrl-C to stop.")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\nStopped.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
